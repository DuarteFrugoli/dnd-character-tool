def update_arb(locale: str, translations: dict) -> None:
    path = os.path.join(L10N_DIR, f'app_{locale}.arb')
    if not os.path.exists(path):
        print(f'  SKIP — file not found: {path}')
        return

    with open(path, encoding='utf-8') as f:
        data = json.load(f)

    changed = 0
    added = 0
    for key, value in translations.items():
        if key in data:
            if data[key] != value:
                data[key] = value
                changed += 1
        else:
            data[key] = value
            added += 1

    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f'  {locale}: {changed} updated, {added} added')


def main():
    print('Updating level-up translations...')
    for locale, translations in TRANSLATIONS.items():
        update_arb(locale, translations)
    print('Done.')


if __name__ == '__main__':
    main()
